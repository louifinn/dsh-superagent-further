#!/usr/bin/env node
// Generate the generated reference pages: the model-facing tools and the settings schema.
//
//   npm run docs:generate          # rewrite docs/reference/tools.md and docs/reference/config.md
//   npm run docs:check             # fail when the committed pages differ from a fresh generation
//
// The tool list is built by calling each tool factory against inert proxies, so the page describes the real Tool objects the
// model sees, not a hand-maintained list. The config page is converted from SettingsSchema with Zod's JSON Schema exporter.
// Both pages say "generated"; edit the code, never the page.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { z } from 'zod'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const reference = path.join(root, 'docs', 'reference')
const check = process.argv.includes('--check')

/** An inert stand-in for any host, project, ticket or record: only reading properties and calling methods is possible. */
const inert = new Proxy(function inert() { /* a factory argument is never used at build time */ }, {
  get(_target, property) {
    if (property === Symbol.toPrimitive) return () => ''
    if (property === 'then') return undefined
    return inert
  },
  apply() { return inert },
})

const { mainTools } = await import('../src/app/tools/main.ts')
const { executorTools } = await import('../src/app/tools/executor.ts')
const { leadTools } = await import('../src/app/tools/lead.ts')
const { automationTools } = await import('../src/app/tools/automation.ts')
const { memoryTools } = await import('../src/app/tools/memory.ts')
const { SettingsSchema } = await import('../src/policy.ts')

const groups = [
  ['Main Session', mainTools(inert, { id: 'main' })],
  ['Executor Session', executorTools(inert, inert)],
  ['Project Lead Session', leadTools(inert, inert)],
  ['The Host schedule service is installed', automationTools(inert, 'main')],
  ['Memory tools', memoryTools(inert)],
]

const header = (title, source) => `<!-- Generated by ${source}; do not edit. Run \`pnpm docs:generate\` after changing the code. -->\n\n# ${title}\n`

function jsonSchema(parameters) {
  try {
    return z.toJSONSchema(parameters, { unrepresentable: 'any', io: 'input', target: 'draft-2020-12' })
  } catch (error) {
    return { note: `No JSON Schema could be derived: ${error instanceof Error ? error.message : String(error)}` }
  }
}

function toolsPage() {
  const lines = [header('Tool reference', 'scripts/generate-tool-reference.mjs'), '', 'Every tool a dsh-superagent-further Session can call, grouped by the role that receives it. A tool is registered only for the Sessions its role names; a disabled feature (for example, memory) removes its tools too. A tool may appear in more than one group when more than one role receives it.', '']
  const seen = new Set()
  let total = 0
  for (const [group, tools] of groups) {
    lines.push(`## ${group}`, '')
    for (const tool of tools) {
      seen.add(tool.name)
      total += 1
      lines.push(`### \`${tool.name}\``, '', tool.description, '', 'Parameters:', '', '```json', JSON.stringify(jsonSchema(tool.schema), null, 2), '```', '')
    }
  }
  lines.push(`## Total`, '', `${seen.size} distinct tools across ${groups.length} groups (${total} registrations).`, '')
  return lines.join('\n')
}

function configPage() {
  const schema = z.toJSONSchema(SettingsSchema, { unrepresentable: 'any', io: 'input', target: 'draft-2020-12' })
  return [header('Settings and configuration reference', 'scripts/generate-tool-reference.mjs'), '', 'The JSON Schema of the settings this plugin accepts, generated from `SettingsSchema` in `src/policy.ts`. The management panel edits these blocks; the Profile supplies the deployment configuration (`Config` in `src/deployment.ts`).', '', '```json', JSON.stringify(schema, null, 2), '```', ''].join('\n')
}

const pages = {
  [path.join(reference, 'tools.md')]: toolsPage(),
  [path.join(reference, 'config.md')]: configPage(),
}

if (check) {
  const drifted = []
  for (const [file, content] of Object.entries(pages)) {
    const relative = path.relative(root, file)
    if (!fs.existsSync(file)) drifted.push(`${relative}: missing`)
    else if (fs.readFileSync(file, 'utf8') !== content) drifted.push(`${relative}: differs from a fresh generation`)
  }
  if (drifted.length) {
    console.error('Generated reference is stale:')
    for (const item of drifted) console.error(`  - ${item}`)
    console.error('Run `pnpm docs:generate` and review the diff.')
    process.exit(1)
  }
  console.log(`docs check: ${Object.keys(pages).length} generated pages are current`)
} else {
  fs.mkdirSync(reference, { recursive: true })
  for (const [file, content] of Object.entries(pages)) fs.writeFileSync(file, content)
  console.log(`docs:generate: wrote ${Object.keys(pages).map(file => path.relative(root, file)).join(', ')}`)
}
